// Shared maze data and constants (Node + browser compatible).
// Single hardcoded 16:9 map: 64 x 36 tiles.
(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) module.exports = factory();
  else root.Maze = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var TILE = 32;
  var MAP_W = 64;
  var MAP_H = 36;

  // Legend:
  //  #  wall            .  floor
  //  1  player 1 start  2  player 2 start
  //  K  key candidate   E  exit candidate
  //  C  coin            P  power-up spawn
  var MAP = [
    '################################################################',
    '#.........#.........#.........#.........#.........#............#',
    '#....C....#....C....#....C....#.E..C....#....C....#....C.......#',
    '#.....#........P....#...#...............#...#P.................#',
    '#...#...............#.........#.........#................2.....#',
    '#....C....#....C.........C....#....C.........C....#....C.......#',
    '#.........#...................#...................#............#',
    '#.........#.........#.........#.........#.........#............#',
    '######..########..########..########..########..########..######',
    '#.........#.........#.........#.........#.........#............#',
    '#....C....#....C....#.........#....C....#....C....#....C.......#',
    '#.........#.........#.........#.........#.........#............#',
    '#...........K.#.....#.............#.....#.....#.......#........#',
    '#....C....#....C....#..............C....#....C....#....C.......#',
    '#.........#.....#.........#...#.....#.............#.....#......#',
    '#.........#...................#...................#............#',
    '######..########..########..########..########..########..######',
    '#.E.......#.........#.........#.P.......#.........#..........E.#',
    '#.........#.........#.........#.........#.........#............#',
    '#....C....#....C....#.........#....C....#....C....#....C.......#',
    '#.........#.........#.....K...#.........#.........#............#',
    '#...................#...................#......................#',
    '#....C.........C....#..............C....#....C.........C.......#',
    '#.........#...................#.P.................#............#',
    '######..########..########..########..########..########..######',
    '#.........#.........#.........#.........#.........#............#',
    '#....C....#....C....#....C....#....C....#....C....#....C.......#',
    '#.........#.........#.........#.........#.........#............#',
    '#.........#.........#.........#.........#.......K.#............#',
    '#...................#...................#......................#',
    '#....C.........C....#....C.........C....#....C.........C.......#',
    '#...1.....#...................#...................#............#',
    '#.........#...................#...................#............#',
    '#....C....#....P....#.........#.E..C....#....P....#....C.......#',
    '#.........#.........#.........#.........#.........#............#',
    '################################################################'
  ];

  function isWall(tx, ty) {
    if (tx < 0 || ty < 0 || tx >= MAP_W || ty >= MAP_H) return true;
    return MAP[ty].charAt(tx) === '#';
  }

  function charAt(tx, ty) {
    if (tx < 0 || ty < 0 || tx >= MAP_W || ty >= MAP_H) return '#';
    return MAP[ty].charAt(tx);
  }

  return {
    TILE: TILE,
    MAP_W: MAP_W,
    MAP_H: MAP_H,
    WIDTH: MAP_W * TILE,
    HEIGHT: MAP_H * TILE,
    MAP: MAP,
    isWall: isWall,
    charAt: charAt
  };
});
